"""
================================================================================
FILE: train_yolo.py
PURPOSE:
    Trains the Ultralytics `YOLOv8n` object detector on the Pascal VOC bounding-
    box subset of IP102 prepared by `prepare_data.py` (`config.YOLO_DATA_YAML`).

    Tailored for a Windows laptop with an NVIDIA RTX 4050 (6 GB VRAM):
      - Checks `torch.cuda.is_available()` and selects GPU `0` or `"cpu"`.
      - Uses `yolov8n.pt` (nano backbone), `imgsz = 512`, `batch = 8`,
        `workers = 2`, and `amp = True` (mixed precision).
      - Supports `--quick-test` (`config.QUICK_TEST_EPOCHS = 2` epochs).
      - Copies the best trained checkpoint (`best.pt`) to
        `config.YOLO_WEIGHTS_PATH` (`models/yolo_pest.pt`).

HOW IT CONNECTS TO OTHER FILES:
    - Reads `config.YOLO_DATA_YAML` generated by `prepare_data.py`.
    - Saves `models/yolo_pest.pt` loaded by `evaluate.py` and `detect.py`.
================================================================================
"""

# Import standard library modules for CLI arguments and file operations
import argparse
import os
import shutil
import sys

# Import central project configuration
import config


# # [YOLO] # [DATASET]
def train_yolo(quick_test: bool = False) -> None:
    """
    Trains Ultralytics YOLOv8n on `config.YOLO_DATA_YAML` and copies `best.pt`
    to `config.YOLO_WEIGHTS_PATH` (`models/yolo_pest.pt`).
    """
    import torch
    from ultralytics import YOLO

    if not os.path.isfile(config.YOLO_DATA_YAML):
        print(
            f"[ERROR] YOLO data.yaml not found at: {config.YOLO_DATA_YAML}\n"
            f"Run `python prepare_data.py` first!"
        )
        sys.exit(1)

    use_cuda = torch.cuda.is_available()
    device_arg = 0 if use_cuda else "cpu"
    if use_cuda:
        gpu_name = torch.cuda.get_device_name(0)
        print(f"[GPU] Training YOLOv8n on CUDA device: {gpu_name}")
    else:
        print("[CPU] CUDA not available; training YOLOv8n on CPU.")

    epochs = config.QUICK_TEST_EPOCHS if quick_test else config.YOLO_EPOCHS
    os.makedirs(config.MODELS_DIR, exist_ok=True)

    model = YOLO(config.YOLO_BASE_WEIGHTS)
    results = model.train(
        data=config.YOLO_DATA_YAML,
        epochs=epochs,
        imgsz=config.YOLO_IMAGE_SIZE,
        batch=config.YOLO_BATCH_SIZE,
        workers=config.DATALOADER_WORKERS,
        device=device_arg,
        amp=True,
        project=os.path.join(config.MODELS_DIR, "yolo_runs"),
        name="ip102_yolov8n",
        exist_ok=True,
    )

    # Copy best.pt to models/yolo_pest.pt
    save_dir = str(getattr(results, "save_dir", ""))
    best_pt = os.path.join(save_dir, "weights", "best.pt")
    if os.path.isfile(best_pt):
        shutil.copy2(best_pt, config.YOLO_WEIGHTS_PATH)
        print(f"\nSaved best YOLOv8n weights to: {config.YOLO_WEIGHTS_PATH}")
    else:
        print(
            f"\n[WARNING] Could not find best.pt at {best_pt}. "
            f"Check { config.MODELS_DIR }/yolo_runs/ip102_yolov8n/weights/."
        )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Train Ultralytics YOLOv8n on IP102 detection subset."
    )
    parser.add_argument(
        "--quick-test",
        action="store_true",
        help=f"Run {config.QUICK_TEST_EPOCHS} epochs to test the pipeline quickly.",
    )
    args = parser.parse_args()
    train_yolo(quick_test=args.quick_test)
